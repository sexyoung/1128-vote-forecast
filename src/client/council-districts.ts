export const councilDistricts: readonly CouncilDistrict[] = Object.entries(districtInputs).flatMap(
  ([jurisdictionId, districts]) =>
    districts.map((district) => ({
      ...district,
      id: `${jurisdictionId}-COUNCIL-${district.number}`,
      jurisdictionId,
    })),
);

export function getCouncilDistricts(jurisdictionId: string) {
  return councilDistricts.filter((district) => district.jurisdictionId === jurisdictionId);
}

export function getRegionalCouncilDistricts(jurisdictionId: string) {
  return getCouncilDistricts(jurisdictionId).filter((district) => district.kind === 'REGIONAL');
}

export function findRegionalCouncilDistricts(
  jurisdictionId: string,
  township: string,
  village?: string,
) {
  return getRegionalCouncilDistricts(jurisdictionId).filter(
    (district) =>
      district.townships.includes(township) ||
      district.villageGroups.some(
        (group) =>
          group.township === township &&
          (village === undefined || group.villages.includes(village)),
      ),
  );
}

export function needsVillageCouncilGeometry(jurisdictionId: string) {
  return getRegionalCouncilDistricts(jurisdictionId).some(
    (district) => district.villageGroups.length > 0,
  );
}
