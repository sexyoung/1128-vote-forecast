// Source of truth: 中選會「中選務字第1153150253號公告」第 3–15 頁。
// Regional districts drive the ordinary geographic map. Indigenous districts overlap those
// regions by elector qualification, so they stay as independent contests and are not inferred
// from a clicked township or village.

export type CouncilDistrictKind = 'REGIONAL' | 'PLAINS_INDIGENOUS' | 'MOUNTAIN_INDIGENOUS';

export type CouncilDistrict = {
  area: string;
  id: string;
  jurisdictionId: string;
  kind: CouncilDistrictKind;
  number: number;
  seats: number;
  townships: readonly string[];
  villageGroups: readonly {
    township: string;
    villages: readonly string[];
  }[];
};

type DistrictInput = Omit<CouncilDistrict, 'id' | 'jurisdictionId'>;

const r = (number: number, seats: number, townships: readonly string[]): DistrictInput => ({
  area: townships.join('、'),
  kind: 'REGIONAL',
  number,
  seats,
  townships,
  villageGroups: [],
});

const rv = (
  number: number,
  seats: number,
  township: string,
  villages: readonly string[],
): DistrictInput => ({
  area: `${township}${villages.join('、')}`,
  kind: 'REGIONAL',
  number,
  seats,
  townships: [],
  villageGroups: [{ township, villages }],
});

const i = (
  number: number,
  seats: number,
  kind: Exclude<CouncilDistrictKind, 'REGIONAL'>,
  area: string,
): DistrictInput => ({ area, kind, number, seats, townships: [], villageGroups: [] });

